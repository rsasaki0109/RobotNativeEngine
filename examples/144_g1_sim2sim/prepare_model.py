#!/usr/bin/env python3
"""Derive RNE's 12-DoF walking G1 from unitree_rl_gym's g1_12dof.urdf.

Two changes, both recorded in the output header:
- The torso mesh torso_link_23dof_rev_1_0.STL (7.8 MB, not vendored) becomes
  the vendored 23-DoF torso_link.STL, raised 10 mm to where the 23-DoF waist
  joint places it. Torso inertia and the (unused) mesh collision are unchanged.
- The four sensor frames without <inertial> (IMUs, D435, MID-360) get the
  1e-9 kg marker inertia used by examples/139_kick_comparison/prepare_models.py.
  URDF gives such links no mass, but RNE's importer would assign each 1 kg.

Usage: prepare_model.py UNITREE_RL_GYM_ROOT
"""
import argparse
import hashlib
import re
from pathlib import Path

SOURCE = "resources/robots/g1_description/g1_12dof.urdf"
SOURCE_SHA256 = "52a0f729252cba764f610136f0772573e55694024b888da93abd5ad23aba0152"
OUTPUT = Path(__file__).resolve().parents[2] / "assets/robots/g1_description/g1_12dof.rne.urdf"
FRAMES = ["imu_in_torso", "imu_in_pelvis", "d435_link", "mid360_link"]
MARKER = ('<link name="{name}">\n    <inertial>\n      <origin xyz="0 0 0" rpy="0 0 0"/>\n'
          '      <mass value="1e-09"/>\n      <inertia ixx="1e-12" ixy="0" ixz="0" '
          'iyy="1e-12" iyz="0" izz="1e-12"/>\n    </inertial>\n  </link>')
TORSO_OLD = ('      <origin xyz="0.0039635 0 -0.044" rpy="0 0 0"/>\n      <geometry>\n'
             '        <mesh filename="meshes/torso_link_23dof_rev_1_0.STL"/>')
TORSO_NEW = ('      <origin xyz="0 0 0.01" rpy="0 0 0"/>\n      <geometry>\n'
             '        <mesh filename="meshes/torso_link.STL"/>')
HEADER = """<!-- RNE derivative of unitreerobotics/unitree_rl_gym
     resources/robots/g1_description/g1_12dof.urdf (BSD-3-Clause, see
     LICENSE.unitree_rl_gym and UPSTREAM.md), generated by
     examples/144_g1_sim2sim/prepare_model.py. The torso visual/collision mesh
     is the vendored 23-DoF torso_link.STL, and the four inertia-less sensor
     frames carry 1e-9 kg marker inertials. Every other inertial, joint, limit
     and foot collision is unchanged. -->
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    raw = (parser.parse_args().upstream / SOURCE).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("Upstream g1_12dof.urdf differs from the audited revision")
    text = raw.decode().replace("\r\n", "\n")
    if text.count(TORSO_OLD) != 2:
        raise ValueError("Unexpected torso geometry")
    text = text.replace(TORSO_OLD, TORSO_NEW)
    for name in FRAMES:
        empty = f'<link name="{name}"></link>'
        if text.count(empty) != 1:
            raise ValueError(f"Unexpected frame link {name}")
        text = text.replace(empty, MARKER.format(name=name))
    # Commented-out links are upstream notes, not model entities.
    live = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    if re.search(r"<link name=\"[^\"]+\"\s*(/>|></link>)", live):
        raise ValueError("An inertia-less link remains")
    OUTPUT.write_text(HEADER + text)
    print(OUTPUT, hashlib.sha256(OUTPUT.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
