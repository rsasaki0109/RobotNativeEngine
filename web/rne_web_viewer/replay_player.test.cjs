const assert=require('node:assert/strict');
const {indexAt,ReplayClock}=require('./replay_player.js');
const times=[0,1,4,17,30,61];
assert.equal(indexAt(times,-1),0);
assert.equal(indexAt(times,0),0);
assert.equal(indexAt(times,3),1);
assert.equal(indexAt(times,4),2);
assert.equal(indexAt(times,29.9),3);
assert.equal(indexAt(times,999),5);
assert.equal(indexAt([0,3,3,9],3),2);
assert.equal(indexAt([0],1),0);
assert.equal(indexAt([],1),0);
const clock=new ReplayClock(4);
assert.equal(clock.advance(1000,1,61),4);
assert.equal(clock.advance(1100,1,61),7);
assert.equal(indexAt(times,clock.tick),2);
assert.equal(clock.advance(1200,2,61),13);
assert.equal(clock.advance(1300,0.5,61),14.5);
assert.equal(clock.advance(1400,4,61),26.5);
assert.equal(clock.advance(10000,4,61),61);
assert.equal(indexAt(times,clock.tick),5);
// A paused/hidden interval must not be carried over into the next presentation.
clock.reset(17);
assert.equal(clock.advance(999999,4,61),17);
assert.equal(clock.advance(1000099,'invalid',61),20);
clock.reset(0);
assert.equal(clock.advance(10,1,0),0);
assert.equal(clock.advance(1000,4,0),0);
assert.deepEqual(times,[0,1,4,17,30,61]);
console.log('PASS: irregular/duplicate saved ticks, playback rates, end clamping, pause rebasing and unchanged snapshots');
