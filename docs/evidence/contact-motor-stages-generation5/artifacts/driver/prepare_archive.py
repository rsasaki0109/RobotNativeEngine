#!/usr/bin/env python3
"""Prepare an unpublished deterministic archive of all eighteen raw gzip files.

The second generated TAR stream is compared byte-for-byte against the first TAR.
Only a PROPOSED local pointer is created; no tag, release or network action exists.
"""

import argparse
import gzip
import hashlib
from pathlib import Path
import tarfile

from durable_common import (
    artifact, BLOCK, fixed_cells, fsync_directory, INDEPENDENCE, literal_json,
    mkdir_new, now, open_new, persistent_path, require, strict_json, sync_stream,
    validate_artifact, validate_spec, write_new_bytes, write_new_json,
)


class HashingReader:
    """Confirm the exact source bytes consumed by tarfile.addfile."""

    def __init__(self, stream):
        self.stream = stream
        self.digest = hashlib.sha256()
        self.count = 0

    def read(self, size=-1):
        content = self.stream.read(size)
        self.digest.update(content)
        self.count += len(content)
        return content


class HashingWriter:
    def __init__(self, stream):
        self.stream = stream
        self.digest = hashlib.sha256()
        self.count = 0

    def write(self, content):
        written = self.stream.write(content)
        require(written == len(content), "short archive write")
        self.digest.update(content)
        self.count += len(content)
        return written


class ComparingWriter:
    """Compare every regenerated byte against a saved original TAR stream."""

    def __init__(self, original):
        self.original = original
        self.digest = hashlib.sha256()
        self.count = 0

    def write(self, content):
        require(self.original.read(len(content)) == content, "second TAR stream differs byte-for-byte")
        self.digest.update(content)
        self.count += len(content)
        return len(content)

    def finish(self):
        require(self.original.read(1) == b"", "second TAR stream is shorter than first")


def gzip_stream_receipt(record):
    """Validate gzip container/trailer and stream hash; never filter numeric rows."""
    validate_artifact(record)
    digest = hashlib.sha256()
    count = 0
    with gzip.open(record["path"], "rb") as stream:
        for content in iter(lambda: stream.read(BLOCK), b""):
            digest.update(content)
            count += len(content)
    validate_artifact(record)
    return {"compressed": record, "uncompressed_bytes": count,
            "uncompressed_stream_sha256": digest.hexdigest(),
            "inspection_scope": "gzip container/trailer and literal uncompressed stream only; no JSON/numerical admission"}


def header(name, size):
    member = tarfile.TarInfo(name)
    member.size = size
    member.mtime = 0
    member.mode = 0o444
    member.uid = member.gid = 0
    member.uname = member.gname = ""
    member.type = tarfile.REGTYPE
    return member


def write_tar_stream(destination, members):
    consumed = []
    with tarfile.open(fileobj=destination, mode="w|", format=tarfile.USTAR_FORMAT) as archive:
        for member in members:
            record = member["artifact"]
            validate_artifact(record)
            with Path(record["path"]).open("rb") as source:
                reader = HashingReader(source)
                archive.addfile(header(member["name"], record["bytes"]), reader)
                require(reader.count == record["bytes"] and reader.digest.hexdigest() == record["sha256"],
                        "TAR consumed source stream does not match frozen member")
                require(source.read(1) == b"", "TAR source grew while streaming")
            validate_artifact(record)
            consumed.append({"name": member["name"], "bytes": reader.count,
                             "sha256": reader.digest.hexdigest()})
    return consumed


def verify_saved_tar(tar_record, members):
    validate_artifact(tar_record)
    observed = []
    with tarfile.open(tar_record["path"], mode="r:") as archive:
        for member in archive:
            require(member.isfile() and member.type == tarfile.REGTYPE, "nonregular TAR member")
            require(member.mtime == 0 and member.uid == member.gid == 0 and member.mode == 0o444
                    and member.uname == member.gname == "", "nondeterministic TAR header")
            stream = archive.extractfile(member)
            digest, count = hashlib.sha256(), 0
            for content in iter(lambda: stream.read(BLOCK), b""):
                digest.update(content)
                count += len(content)
            observed.append({"name": member.name, "bytes": count, "sha256": digest.hexdigest()})
    expected = [{"name": row["name"], "bytes": row["artifact"]["bytes"],
                 "sha256": row["artifact"]["sha256"]} for row in members]
    require(observed == expected, "saved TAR literal member order/size/SHA differs")
    require(len(observed) == 19 and len({row["name"] for row in observed}) == 19, "TAR member count/identity differs")
    return observed


def prepare(spec_record):
    spec, _bindings, _expected = validate_spec(spec_record)
    root = persistent_path(spec["cohort_root"])
    final = root / "collection-terminal.json"
    terminal = strict_json(final)
    require(terminal.get("cohort_id") == spec["cohort_id"] and terminal.get("frozen_spec") == spec_record
            and terminal.get("independence") == INDEPENDENCE, "wrong collection terminal identity")
    validate_artifact(terminal["index"], beneath=root)
    index = strict_json(terminal["index"]["path"])
    require(index.get("cohort_id") == spec["cohort_id"] and index.get("frozen_spec") == spec_record
            and index.get("independence") == INDEPENDENCE, "wrong collection index identity")
    require(index.get("worlds_attempted") == 18 and len(index.get("case_receipts", [])) == 18,
            "archive requires every fixed case's original process and terminal receipt")
    require([{key: row[key] for key in ("build", "mass_kg", "mode", "run_label")}
             for row in index["runs"]] == fixed_cells(), "archive matrix/order differs")
    case_rows = []
    for ordinal, (row, receipt_record) in enumerate(zip(index["runs"], index["case_receipts"])):
        validate_artifact(receipt_record, beneath=root)
        receipt = strict_json(receipt_record["path"])
        require(receipt.get("case_index") == ordinal and receipt.get("cohort_id") == spec["cohort_id"]
                and receipt.get("row") == row and receipt.get("original_exit_code") == row["exit_code"],
                "case receipt/index/exit binding differs")
        require(receipt.get("process_started") is True and receipt.get("source_inputs_unchanged") is True,
                "case has incomplete process or changed provenance")
        validate_artifact(receipt["original_process_exit_receipt"], beneath=root)
        actual_exit = strict_json(receipt["original_process_exit_receipt"]["path"])
        require(actual_exit.get("case_index") == ordinal
                and actual_exit.get("original_exit_code") == row["exit_code"],
                "durable original process exit differs")
        for role in ("trace", "stdout", "stderr", "source_guard_before", "source_guard_after"):
            validate_artifact(row[role], beneath=root)
        require(row["trace"]["path"] == str(root / "raw" / (row["run_label"] + ".jsonl.gz")),
                "raw output path differs from fixed cohort cell")
        require(strict_json(row["source_guard_before"]["path"]) == strict_json(row["source_guard_after"]["path"]),
                "case source before/after differs")
        case_rows.append({"case_index": ordinal, **{key: row[key] for key in
                          ("build", "mass_kg", "mode", "run_label")},
                          "name": row["run_label"] + ".jsonl.gz", "bytes": row["trace"]["bytes"],
                          "sha256": row["trace"]["sha256"], "original_exit_code": row["exit_code"]})
    # The archive operation has its own permanent once-only claim. Failed or
    # partial TARs remain at their original paths and are never deleted/replaced.
    destination = root / "archive-preparation"
    mkdir_new(destination)
    write_new_json(destination / "archive-claim.json", {
        "cohort_id": spec["cohort_id"], "started_utc": now(), "frozen_spec": spec_record,
        "collection_index": terminal["index"], "publication_status": "PROPOSED_ONLY",
        "independence": INDEPENDENCE, "retry_or_overwrite_permitted": False,
    })
    try:
        stream_receipts = [gzip_stream_receipt(row["trace"]) for row in index["runs"]]
        write_new_json(destination / "actual-gzip-stream-verification.json", {
            "cohort_id": spec["cohort_id"], "streams": stream_receipts,
            "numeric_selection_performed": False,
        })
        manifest = {
            "schema_version": 1, "generation": 5, "cohort_id": spec["cohort_id"],
            "independence": INDEPENDENCE, "members": case_rows,
            "raw_gzip_members": 18, "numerical_admission_claim": None,
        }
        manifest_record = write_new_bytes(destination / "literal-member-manifest.json", literal_json(manifest))
        members = [{"name": row["run_label"] + ".jsonl.gz", "artifact": row["trace"]}
                   for row in index["runs"]]
        members.append({"name": "literal-member-manifest.json", "artifact": manifest_record})
        tar_path = destination / "contact-motor-stages-generation5-raw.tar"
        with open_new(tar_path) as saved:
            first = HashingWriter(saved)
            consumed_first = write_tar_stream(first, members)
            sync_stream(saved)
        fsync_directory(destination)
        tar_record = artifact(tar_path)
        require(tar_record["bytes"] == first.count and tar_record["sha256"] == first.digest.hexdigest(),
                "saved first TAR stream hash/size differs")
        observed = verify_saved_tar(tar_record, members)
        with tar_path.open("rb") as original:
            second = ComparingWriter(original)
            consumed_second = write_tar_stream(second, members)
            second.finish()
        require(second.count == first.count and second.digest.hexdigest() == first.digest.hexdigest()
                and consumed_second == consumed_first, "second TAR stream does not equal first")
        validate_artifact(tar_record)
        validate_spec(spec_record)
        verification = write_new_json(destination / "archive-verification.json", {
            "status": "PASS_LITERAL_ARCHIVE_INTEGRITY_SECOND_STREAM_BYTE_IDENTICAL",
            "cohort_id": spec["cohort_id"], "archive": tar_record, "literal_manifest": manifest_record,
            "members": observed, "first_stream_bytes": first.count,
            "first_stream_sha256": first.digest.hexdigest(), "second_stream_bytes": second.count,
            "second_stream_sha256": second.digest.hexdigest(), "second_stream_byte_comparison": True,
            "raw_originals_preserved": True, "gzip_streams_verified": 18,
            "process_exit_codes_selected_or_changed": False, "numerical_admission_claim": None,
            "native_worlds_executed_by_archive_helper": 0,
        })
        pointer = write_new_json(destination / "proposed-archive-pointer.json", {
            "schema_version": 1, "status": "PROPOSED_LOCAL_ARCHIVE_NOT_PUBLISHED",
            "generation": 5, "cohort_id": spec["cohort_id"], "independence": INDEPENDENCE,
            "archive": tar_record, "literal_member_manifest": manifest_record,
            "verification": verification, "collection_index": terminal["index"],
            "collection_status": index["status"], "frozen_spec": spec_record,
            "remote_url": None, "tag": None, "release_asset_uploaded": False,
            "restores_lost_generation4_archive": False, "numerical_admission_claim": None,
        })
        write_new_json(destination / "archive-terminal.json", {
            "exit_code": 0, "ended_utc": now(), "pointer": pointer,
            "publication_status": "PROPOSED_ONLY", "native_worlds": 0,
        })
        return pointer
    except Exception as error:
        failed = {
            "exit_code": 1, "ended_utc": now(), "error": f"{type(error).__name__}: {error}",
            "original_files_and_partial_tar_preserved": True,
            "pointer_created": (destination / "proposed-archive-pointer.json").exists(),
            "publication_status": "NOT_PUBLISHED", "native_worlds": 0,
        }
        # An interrupted exclusive write may already have left a partial
        # terminal file. Keep it literally; append a separate failure receipt.
        write_new_json(destination / "archive-failure.json", failed)
        if not (destination / "archive-terminal.json").exists():
            write_new_json(destination / "archive-terminal.json", failed)
        raise


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--spec", required=True)
    parser.add_argument("--spec-sha256", required=True)
    args = parser.parse_args()
    record = artifact(args.spec)
    require(record["sha256"] == args.spec_sha256, "frozen driver spec SHA mismatch")
    import json
    print(json.dumps(prepare(record), sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
